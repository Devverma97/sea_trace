// Generate realistic poly around centroid
function createPolygon(center: { lat: number; lng: number }, areaKm2: number): { lat: number; lng: number }[] {
  const radius = Math.sqrt(areaKm2 / Math.PI) / 111.32; // in degrees
  const points = [];
  const steps = 14;
  for (let i = 0; i < steps; i++) {
    const angle = (i / steps) * 2 * Math.PI;
    // slightly irregular shape resembling an elongated slick
    const elongation = 1.6 + 0.4 * Math.sin(2 * angle);
    const jitter = 0.85 + 0.3 * Math.cos(3 * angle);
    const r = radius * elongation * jitter;
    // rotate slick along wind/current axis (e.g. 45 deg)
    const rot = (45 * Math.PI) / 180;
    const dx = r * Math.cos(angle);
    const dy = r * Math.sin(angle);
    const rx = dx * Math.cos(rot) - dy * Math.sin(rot);
    const ry = dx * Math.sin(rot) + dy * Math.cos(rot);
    points.push({
      lat: Number((center.lat + ry).toFixed(5)),
      lng: Number((center.lng + rx).toFixed(5)),
    });
  }
  // close polygon
  points.push(points[0]);
  return points;
}

